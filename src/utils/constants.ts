export function getJuzForPage(page: number, mode: '15-line' | '16-line'): number {
  const map = mode === '16-line' ? JUZ_PAGE_MAP_16LINE : JUZ_PAGE_MAP_15LINE;
  let juz = 1;
  for (let j = 1; j <= 30; j++) {
    if (map[j] <= page) juz = j;
    else break;
  }
  return juz;
}

export function getSurahForPage(page: number): SurahInfo {
  let surah = SURAH_LIST[0];
  for (const s of SURAH_LIST) {
    if (s.page <= page) surah = s;
    else break;
  }
  return surah;
}

